void Send_Font_Byte(unsigned char Data)
{
    unsigned char i;
    unsigned char temp;
    
    for (i = 0; i < 4; i++)
    {
        temp = 0x00;
        
        // [修改] 不要再寫死 0xF0 跟 0x0F，改用我們自訂的亮度變數！
        if (Data & 0x80) temp |= (g_u8TextBrightness << 4); // 左像素
        if (Data & 0x40) temp |= g_u8TextBrightness;        // 右像素
        
        vWriteData(temp); 
        Data <<= 2; 
    }
}

void vPrintLogNumber(char *str,...)
{
	uint8_t i,j;
	char word[11] = {0,};
	
	va_list argptr;
	va_start(argptr, str);
	vsprintf(word, str, argptr); // 注意：需確保字串不超過10個字，否則溢出
	va_end(argptr);
	
	for(i = 0; i < 10; i++)
	{
		if(word[i] == 0) return;
		
        // 設定寫入視窗 (Column)
		vWriteCommand(0x15);   
		vWriteData(0x1c  + i*4);
		vWriteData(0x1c + i*4 + 3);
		vWriteCommand(0x75);   // set raw address
		vWriteData(00);
		vWriteData(0x3f);
		vWriteCommand(0x5c);   // write ram command
		
		for(j = 0; j < 64; j+=1)
		{
            if(word[i] == ' ') {
                // 空白字元直接填 0 (需填入4個byte因為原本邏輯是展開8個bit)
                vWriteData(0x00); vWriteData(0x00); vWriteData(0x00); vWriteData(0x00);
            } else {
                // 使用封裝好的函式發送資料，邏輯更清晰，減少重複代碼
                Send_Font_Byte(font_16x32[(word[i] - 0x30) * 64 + j]);
            }
		}
	}
}

